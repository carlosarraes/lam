import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const read = name => readFileSync(new URL(name, import.meta.url));
const json = name => JSON.parse(read(name));
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const run = json('run-8bc82a6.json');
const history = json('history-8bc82a6.json').data.events.map(row => row.event);
const messages = history.filter(row => row.kind === 'message').map(row => row.message);
const receipts = history.filter(row => row.kind === 'receipt');
assert.equal(messages.length, 2);
assert.equal(receipts.length, 4);
assert.deepEqual(receipts.map(row => row.state), ['submitting', 'unknown', 'submitting', 'unknown']);
const peer = messages.find(row => row.id === '6b5c7d20-d94e-4aa9-a08f-f4eecc555367');
const attempt = json('attempted-reply-8bc82a6.json');
const prefix = '--message \'';
assert.ok(attempt.command.endsWith("'"));
const literal = attempt.command.slice(attempt.command.indexOf(prefix) + prefix.length, -1);
assert.equal(literal, peer.draft.body);
assert.equal(Buffer.byteLength(literal), 4096);
assert.equal(sha(literal), run.bodyComparison.sha256);
assert.equal(run.bodyComparison.replyPersisted, false);
assert.equal(run.bodyComparison.childAutomaticReplyObserved, false);
assert.equal(sha(read('hooks-8bc82a6.json')), run.hookConfigSha256);
assert.equal(sha(read('chat.toml')), run.chatConfigSha256);
assert.equal(sha(read('empty-checks.mjs')), run.benchmark.scriptSha256);
const timing = json('timing-8bc82a6.json');
assert.equal(timing.nativeThread, run.probe.nativeThread);
assert.equal(timing.count, 100);
assert.equal(timing.samplesMs.length, 100);
assert.equal(timing.stdoutBytes, 0);
assert.equal(timing.stderrBytes, 0);
const sorted = [...timing.samplesMs].sort((a, b) => a - b);
assert.equal(timing.medianMs, (sorted[49] + sorted[50]) / 2);
assert.equal(timing.p95Ms, sorted[94]);
assert.equal(timing.maxMs, sorted[99]);
assert.ok(timing.maxMs < 50);
assert.equal(run.bindings.find(row => row.native_id === timing.nativeThread).observation_epoch, 104);
assert.ok(run.attempts.every(row => row.encodedBytes <= 8192));
console.log('Native hook evidence checks passed; refused reply and remaining gates stay unproven.');
